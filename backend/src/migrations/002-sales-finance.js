import { table } from './table.js';

export const salesFinanceTables = [
  table('parties', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(180) NOT NULL,
    is_customer BOOLEAN NOT NULL DEFAULT FALSE,
    is_supplier BOOLEAN NOT NULL DEFAULT FALSE,
    phone VARCHAR(40) NULL,
    credit_limit_minor BIGINT UNSIGNED NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (is_customer OR is_supplier)`),
  table('party_accounts', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    party_id BIGINT UNSIGNED NOT NULL,
    account_type ENUM('receivable','payable') NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'TRY',
    UNIQUE (party_id, account_type, currency),
    FOREIGN KEY (party_id) REFERENCES parties(id),
    CHECK (currency = 'TRY')`),
  table('dining_sections', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    sort_order INT NOT NULL DEFAULT 0`),
  table('dining_tables', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    section_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(80) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (section_id, name),
    FOREIGN KEY (section_id) REFERENCES dining_sections(id)`),
  table('settlement_groups', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    status ENUM('open','closed','merged') NOT NULL DEFAULT 'open',
    merged_into_id BIGINT UNSIGNED NULL,
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    opened_by BIGINT UNSIGNED NOT NULL,
    opened_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    closed_at_utc DATETIME(6) NULL,
    FOREIGN KEY (merged_into_id) REFERENCES settlement_groups(id),
    FOREIGN KEY (opened_by) REFERENCES app_users(id),
    CHECK ((status = 'merged' AND merged_into_id IS NOT NULL) OR (status <> 'merged' AND merged_into_id IS NULL)),
    INDEX ix_groups_status (status, opened_at_utc)`),
  table('checks', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    check_number VARCHAR(40) NOT NULL UNIQUE,
    check_type ENUM('table','retail') NOT NULL,
    status ENUM('open','closed','cancelled') NOT NULL DEFAULT 'open',
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    opened_by BIGINT UNSIGNED NOT NULL,
    opened_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    closed_at_utc DATETIME(6) NULL,
    FOREIGN KEY (opened_by) REFERENCES app_users(id),
    INDEX ix_checks_status_time (status, opened_at_utc)`),
  table('settlement_group_memberships', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    group_id BIGINT UNSIGNED NOT NULL,
    check_id BIGINT UNSIGNED NOT NULL,
    operation_id BIGINT UNSIGNED NOT NULL,
    joined_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    left_at_utc DATETIME(6) NULL,
    active_check_id BIGINT UNSIGNED GENERATED ALWAYS AS (IF(left_at_utc IS NULL, check_id, NULL)) STORED,
    UNIQUE (active_check_id),
    UNIQUE (id, group_id, check_id),
    FOREIGN KEY (group_id) REFERENCES settlement_groups(id),
    FOREIGN KEY (check_id) REFERENCES checks(id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    CHECK (left_at_utc IS NULL OR left_at_utc >= joined_at_utc),
    INDEX ix_group_members (group_id, left_at_utc)`),
  table('table_assignments', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    table_id BIGINT UNSIGNED NOT NULL,
    group_id BIGINT UNSIGNED NOT NULL,
    operation_id BIGINT UNSIGNED NOT NULL,
    assigned_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    released_at_utc DATETIME(6) NULL,
    active_table_id BIGINT UNSIGNED GENERATED ALWAYS AS (IF(released_at_utc IS NULL, table_id, NULL)) STORED,
    active_group_id BIGINT UNSIGNED GENERATED ALWAYS AS (IF(released_at_utc IS NULL, group_id, NULL)) STORED,
    UNIQUE (active_table_id),
    UNIQUE (active_group_id),
    FOREIGN KEY (table_id) REFERENCES dining_tables(id),
    FOREIGN KEY (group_id) REFERENCES settlement_groups(id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    CHECK (released_at_utc IS NULL OR released_at_utc >= assigned_at_utc)`),
  table('group_merges', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    source_group_id BIGINT UNSIGNED NOT NULL UNIQUE,
    target_group_id BIGINT UNSIGNED NOT NULL,
    operation_id BIGINT UNSIGNED NOT NULL UNIQUE,
    merged_by BIGINT UNSIGNED NOT NULL,
    reason VARCHAR(500) NOT NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    FOREIGN KEY (source_group_id) REFERENCES settlement_groups(id),
    FOREIGN KEY (target_group_id) REFERENCES settlement_groups(id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    FOREIGN KEY (merged_by) REFERENCES app_users(id),
    CHECK (source_group_id <> target_group_id)`),
  table('order_batches', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    check_id BIGINT UNSIGNED NOT NULL,
    operation_id BIGINT UNSIGNED NOT NULL UNIQUE,
    submitted_by BIGINT UNSIGNED NOT NULL,
    submitted_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE (id, check_id),
    FOREIGN KEY (check_id) REFERENCES checks(id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    FOREIGN KEY (submitted_by) REFERENCES app_users(id)`),
  table('check_lines', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    check_id BIGINT UNSIGNED NOT NULL,
    batch_id BIGINT UNSIGNED NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    option_version_id BIGINT UNSIGNED NOT NULL,
    recipe_version_id BIGINT UNSIGNED NULL,
    product_name VARCHAR(180) NOT NULL,
    option_name VARCHAR(120) NOT NULL,
    unit_code VARCHAR(20) NOT NULL,
    quantity DECIMAL(18,6) NOT NULL,
    unit_price_minor BIGINT UNSIGNED NOT NULL,
    price_basis_quantity DECIMAL(18,6) NOT NULL DEFAULT 1,
    content_quantity_base DECIMAL(18,6) NULL,
    subtotal_minor BIGINT UNSIGNED NOT NULL,
    discount_minor BIGINT UNSIGNED NOT NULL DEFAULT 0,
    total_minor BIGINT UNSIGNED NOT NULL,
    note VARCHAR(1000) NULL,
    added_by BIGINT UNSIGNED NOT NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE (id, check_id),
    FOREIGN KEY (check_id) REFERENCES checks(id),
    FOREIGN KEY (batch_id, check_id) REFERENCES order_batches(id, check_id),
    FOREIGN KEY (option_version_id, product_id) REFERENCES sale_option_versions(id, product_id),
    FOREIGN KEY (recipe_version_id, product_id) REFERENCES recipe_versions(id, product_id),
    FOREIGN KEY (added_by) REFERENCES app_users(id),
    CHECK (quantity > 0 AND price_basis_quantity > 0),
    CHECK (content_quantity_base IS NULL OR content_quantity_base > 0),
    CHECK (discount_minor <= subtotal_minor AND total_minor + discount_minor = subtotal_minor)`),
  table('order_line_events', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    check_line_id BIGINT UNSIGNED NOT NULL,
    operation_id BIGINT UNSIGNED NOT NULL,
    event_type ENUM('submitted','preparing','ready','delivered','cancelled') NOT NULL,
    actor_user_id BIGINT UNSIGNED NOT NULL,
    reason VARCHAR(500) NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE (check_line_id, operation_id, event_type),
    FOREIGN KEY (check_line_id) REFERENCES check_lines(id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    FOREIGN KEY (actor_user_id) REFERENCES app_users(id),
    CHECK (event_type <> 'cancelled' OR (reason IS NOT NULL AND CHAR_LENGTH(TRIM(reason)) > 0)),
    INDEX ix_order_event_time (check_line_id, created_at_utc)`),
  table('preparation_tickets', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    check_line_id BIGINT UNSIGNED NOT NULL,
    station_id BIGINT UNSIGNED NOT NULL,
    status ENUM('new','preparing','ready','delivered','cancelled') NOT NULL DEFAULT 'new',
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    UNIQUE (check_line_id, station_id),
    FOREIGN KEY (check_line_id) REFERENCES check_lines(id),
    FOREIGN KEY (station_id) REFERENCES preparation_stations(id),
    INDEX ix_tickets_station_status (station_id, status)`),
  table('sale_adjustments', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    check_line_id BIGINT UNSIGNED NOT NULL,
    operation_id BIGINT UNSIGNED NOT NULL,
    adjustment_type ENUM('cancel','return','complimentary','discount') NOT NULL,
    quantity DECIMAL(18,6) NULL,
    amount_minor BIGINT UNSIGNED NOT NULL,
    reason VARCHAR(500) NOT NULL,
    approval_id BIGINT UNSIGNED NULL,
    actor_user_id BIGINT UNSIGNED NOT NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    FOREIGN KEY (check_line_id) REFERENCES check_lines(id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    FOREIGN KEY (approval_id) REFERENCES approval_requests(id),
    FOREIGN KEY (actor_user_id) REFERENCES app_users(id),
    CHECK (quantity IS NULL OR quantity > 0),
    CHECK (CHAR_LENGTH(TRIM(reason)) > 0),
    UNIQUE (operation_id, check_line_id, adjustment_type)`),
  table('payments', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    operation_id BIGINT UNSIGNED NOT NULL,
    sequence_no INT UNSIGNED NOT NULL,
    method ENUM('cash','card') NOT NULL,
    direction ENUM('in','out') NOT NULL,
    amount_minor BIGINT UNSIGNED NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'TRY',
    received_by BIGINT UNSIGNED NOT NULL,
    shift_id BIGINT UNSIGNED NULL,
    reversal_of_id BIGINT UNSIGNED NULL,
    external_reference VARCHAR(120) NULL,
    reason VARCHAR(500) NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE (operation_id, sequence_no),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    FOREIGN KEY (received_by) REFERENCES app_users(id),
    FOREIGN KEY (shift_id) REFERENCES cash_shifts(id),
    FOREIGN KEY (reversal_of_id) REFERENCES payments(id),
    CHECK (amount_minor > 0 AND currency = 'TRY'),
    INDEX ix_payments_method_time (method, created_at_utc)`),
  table('party_entries', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    account_id BIGINT UNSIGNED NOT NULL,
    operation_id BIGINT UNSIGNED NOT NULL,
    sequence_no INT UNSIGNED NOT NULL,
    entry_type ENUM('opening','sale_credit','purchase','expense','payment','return','correction','advance') NOT NULL,
    amount_minor BIGINT NOT NULL,
    due_date DATE NULL,
    reversal_of_id BIGINT UNSIGNED NULL,
    description VARCHAR(500) NOT NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE (operation_id, sequence_no),
    FOREIGN KEY (account_id) REFERENCES party_accounts(id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    FOREIGN KEY (reversal_of_id) REFERENCES party_entries(id),
    CHECK (amount_minor <> 0),
    INDEX ix_party_entries_account_time (account_id, created_at_utc),
    INDEX ix_party_entries_due (due_date, account_id)`),
  table('bill_settlements', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    group_id BIGINT UNSIGNED NOT NULL,
    payment_id BIGINT UNSIGNED NULL,
    credit_entry_id BIGINT UNSIGNED NULL UNIQUE,
    direction ENUM('settle','refund') NOT NULL,
    amount_minor BIGINT UNSIGNED NOT NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE (id, group_id),
    UNIQUE (payment_id, group_id),
    FOREIGN KEY (group_id) REFERENCES settlement_groups(id),
    FOREIGN KEY (payment_id) REFERENCES payments(id),
    FOREIGN KEY (credit_entry_id) REFERENCES party_entries(id),
    CHECK (amount_minor > 0),
    CHECK ((payment_id IS NOT NULL) + (credit_entry_id IS NOT NULL) = 1)`),
  table('settlement_allocations', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    settlement_id BIGINT UNSIGNED NOT NULL,
    group_id BIGINT UNSIGNED NOT NULL,
    membership_id BIGINT UNSIGNED NOT NULL,
    check_id BIGINT UNSIGNED NOT NULL,
    check_line_id BIGINT UNSIGNED NULL,
    quantity DECIMAL(18,6) NULL,
    amount_minor BIGINT UNSIGNED NOT NULL,
    FOREIGN KEY (settlement_id, group_id) REFERENCES bill_settlements(id, group_id),
    FOREIGN KEY (membership_id, group_id, check_id) REFERENCES settlement_group_memberships(id, group_id, check_id),
    FOREIGN KEY (check_line_id, check_id) REFERENCES check_lines(id, check_id),
    CHECK (check_line_id IS NOT NULL OR amount_minor > 0),
    CHECK ((check_line_id IS NULL AND quantity IS NULL) OR (check_line_id IS NOT NULL AND quantity IS NOT NULL AND quantity > 0)),
    INDEX ix_allocations_line (check_line_id)`),
  table('party_payment_allocations', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    payment_id BIGINT UNSIGNED NOT NULL,
    party_entry_id BIGINT UNSIGNED NOT NULL,
    amount_minor BIGINT UNSIGNED NOT NULL,
    UNIQUE (payment_id, party_entry_id),
    FOREIGN KEY (payment_id) REFERENCES payments(id),
    FOREIGN KEY (party_entry_id) REFERENCES party_entries(id),
    CHECK (amount_minor > 0)`),
  table('cash_payment_links', `
    payment_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
    cash_movement_id BIGINT UNSIGNED NOT NULL UNIQUE,
    FOREIGN KEY (payment_id) REFERENCES payments(id),
    FOREIGN KEY (cash_movement_id) REFERENCES cash_movements(id)`)
];
