import { table } from './table.js';

export const coreCatalogTables = [
  table('app_users', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    login_name VARCHAR(80) NOT NULL UNIQUE,
    display_name VARCHAR(160) NOT NULL,
    password_hash VARCHAR(255) NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6))`),
  table('roles', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL`),
  table('permissions', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(255) NOT NULL`),
  table('user_roles', `
    user_id BIGINT UNSIGNED NOT NULL,
    role_id BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (user_id, role_id),
    FOREIGN KEY (user_id) REFERENCES app_users(id),
    FOREIGN KEY (role_id) REFERENCES roles(id)`),
  table('role_permissions', `
    role_id BIGINT UNSIGNED NOT NULL,
    permission_id BIGINT UNSIGNED NOT NULL,
    amount_limit_minor BIGINT UNSIGNED NULL,
    requires_approval BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (role_id, permission_id),
    FOREIGN KEY (role_id) REFERENCES roles(id),
    FOREIGN KEY (permission_id) REFERENCES permissions(id)`),
  table('user_sessions', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT UNSIGNED NOT NULL,
    token_hash BINARY(32) NOT NULL UNIQUE,
    device_label VARCHAR(100) NULL,
    expires_at_utc DATETIME(6) NOT NULL,
    revoked_at_utc DATETIME(6) NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    FOREIGN KEY (user_id) REFERENCES app_users(id),
    INDEX ix_sessions_user_expiry (user_id, expires_at_utc)`),
  table('business_operations', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    request_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
    request_hash BINARY(32) NOT NULL,
    operation_type VARCHAR(80) NOT NULL,
    actor_user_id BIGINT UNSIGNED NULL,
    status ENUM('pending','completed','rejected') NOT NULL DEFAULT 'pending',
    result_json JSON NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    completed_at_utc DATETIME(6) NULL,
    FOREIGN KEY (actor_user_id) REFERENCES app_users(id),
    INDEX ix_operations_actor_time (actor_user_id, created_at_utc)`),
  table('units', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(80) NOT NULL,
    dimension ENUM('count','mass','volume','portion','package') NOT NULL,
    decimal_places TINYINT UNSIGNED NOT NULL DEFAULT 0,
    CHECK (decimal_places <= 6)`),
  table('warehouses', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE`),
  table('product_categories', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    sort_order INT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE`),
  table('preparation_stations', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE`),
  table('products', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(180) NOT NULL,
    category_id BIGINT UNSIGNED NULL,
    product_type ENUM('ready','prepared','ingredient','consumable') NOT NULL,
    stock_mode ENUM('none','direct','recipe') NOT NULL,
    stock_timing ENUM('sale','submission','preparation','manual') NOT NULL,
    base_unit_id BIGINT UNSIGNED NULL,
    preparation_station_id BIGINT UNSIGNED NULL,
    track_lots BOOLEAN NOT NULL DEFAULT FALSE,
    reorder_quantity DECIMAL(18,6) NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    FOREIGN KEY (category_id) REFERENCES product_categories(id),
    FOREIGN KEY (base_unit_id) REFERENCES units(id),
    FOREIGN KEY (preparation_station_id) REFERENCES preparation_stations(id),
    CHECK (stock_mode = 'none' OR base_unit_id IS NOT NULL),
    CHECK (reorder_quantity IS NULL OR reorder_quantity >= 0),
    INDEX ix_products_active_name (is_active, name)`),
  table('product_unit_conversions', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    product_id BIGINT UNSIGNED NOT NULL,
    from_unit_id BIGINT UNSIGNED NOT NULL,
    base_quantity DECIMAL(18,6) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (product_id, from_unit_id),
    FOREIGN KEY (product_id) REFERENCES products(id),
    FOREIGN KEY (from_unit_id) REFERENCES units(id),
    CHECK (base_quantity > 0)`),
  table('sale_options', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    product_id BIGINT UNSIGNED NOT NULL,
    code VARCHAR(80) NOT NULL,
    name VARCHAR(120) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (product_id, code),
    UNIQUE (id, product_id),
    FOREIGN KEY (product_id) REFERENCES products(id)`),
  table('sale_option_versions', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    sale_option_id BIGINT UNSIGNED NOT NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    version INT UNSIGNED NOT NULL,
    sale_unit_id BIGINT UNSIGNED NOT NULL,
    unit_price_minor BIGINT UNSIGNED NOT NULL,
    price_basis_quantity DECIMAL(18,6) NOT NULL DEFAULT 1,
    content_quantity_base DECIMAL(18,6) NULL,
    requires_weight BOOLEAN NOT NULL DEFAULT FALSE,
    valid_from_utc DATETIME(6) NOT NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    UNIQUE (sale_option_id, version),
    UNIQUE (sale_option_id, valid_from_utc),
    UNIQUE (id, product_id),
    FOREIGN KEY (sale_option_id, product_id) REFERENCES sale_options(id, product_id),
    FOREIGN KEY (sale_unit_id) REFERENCES units(id),
    FOREIGN KEY (created_by) REFERENCES app_users(id),
    CHECK (version > 0 AND price_basis_quantity > 0),
    CHECK (content_quantity_base IS NULL OR content_quantity_base > 0),
    INDEX ix_option_validity (sale_option_id, valid_from_utc)`),
  table('sale_option_components', `
    option_version_id BIGINT UNSIGNED NOT NULL,
    component_product_id BIGINT UNSIGNED NOT NULL,
    quantity_base DECIMAL(18,6) NOT NULL,
    PRIMARY KEY (option_version_id, component_product_id),
    FOREIGN KEY (option_version_id) REFERENCES sale_option_versions(id),
    FOREIGN KEY (component_product_id) REFERENCES products(id),
    CHECK (quantity_base > 0)`),
  table('product_barcodes', `
    barcode VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
    product_id BIGINT UNSIGNED NOT NULL,
    sale_option_id BIGINT UNSIGNED NULL,
    FOREIGN KEY (product_id) REFERENCES products(id),
    FOREIGN KEY (sale_option_id, product_id) REFERENCES sale_options(id, product_id)`),
  table('product_favorites', `
    product_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
    marked_by BIGINT UNSIGNED NOT NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    FOREIGN KEY (product_id) REFERENCES products(id),
    FOREIGN KEY (marked_by) REFERENCES app_users(id)`),
  table('recipes', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    product_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(160) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (id, product_id),
    FOREIGN KEY (product_id) REFERENCES products(id)`),
  table('recipe_versions', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    recipe_id BIGINT UNSIGNED NOT NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    version INT UNSIGNED NOT NULL,
    output_quantity_base DECIMAL(18,6) NOT NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE (recipe_id, version),
    UNIQUE (id, product_id),
    FOREIGN KEY (recipe_id, product_id) REFERENCES recipes(id, product_id),
    FOREIGN KEY (created_by) REFERENCES app_users(id),
    CHECK (version > 0 AND output_quantity_base > 0)`),
  table('recipe_ingredients', `
    recipe_version_id BIGINT UNSIGNED NOT NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    quantity_base DECIMAL(18,6) NOT NULL,
    PRIMARY KEY (recipe_version_id, product_id),
    FOREIGN KEY (recipe_version_id) REFERENCES recipe_versions(id),
    FOREIGN KEY (product_id) REFERENCES products(id),
    CHECK (quantity_base > 0)`),
  table('sale_option_recipes', `
    option_version_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
    recipe_version_id BIGINT UNSIGNED NOT NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    recipe_multiplier DECIMAL(18,6) NOT NULL DEFAULT 1,
    FOREIGN KEY (option_version_id, product_id) REFERENCES sale_option_versions(id, product_id),
    FOREIGN KEY (recipe_version_id, product_id) REFERENCES recipe_versions(id, product_id),
    CHECK (recipe_multiplier > 0)`)
];
