import { table } from './table.js';

// Operational payloads are metadata/caches. Canonical sales, money and stock
// remain relational records; never place credentials or raw exception text here.
export const operationsTables = [
  table('file_attachments', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    storage_key VARCHAR(500) COLLATE utf8mb4_bin NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    media_type VARCHAR(150) CHARACTER SET ascii NOT NULL,
    size_bytes BIGINT UNSIGNED NOT NULL,
    uploaded_by_user_id BIGINT UNSIGNED NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE KEY uq_attachment_storage (storage_key),
    KEY ix_attachment_hash (sha256),
    FOREIGN KEY (uploaded_by_user_id) REFERENCES app_users(id),
    CHECK (CHAR_LENGTH(storage_key) > 0),
    CHECK (CHAR_LENGTH(sha256) = 64)
  `),

  table('approval_requests', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    operation_id BIGINT UNSIGNED NULL,
    action_code VARCHAR(100) CHARACTER SET ascii NOT NULL,
    requested_by_user_id BIGINT UNSIGNED NOT NULL,
    decided_by_user_id BIGINT UNSIGNED NULL,
    status ENUM('pending','approved','rejected','cancelled') NOT NULL DEFAULT 'pending',
    reason VARCHAR(1000) NOT NULL,
    decision_reason VARCHAR(1000) NULL,
    amount_minor BIGINT NULL,
    quantity DECIMAL(20,6) NULL,
    quantity_unit_code VARCHAR(30) CHARACTER SET ascii NULL,
    decided_at_utc DATETIME(6) NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    KEY ix_approval_queue (status, created_at_utc),
    KEY ix_approval_operation (operation_id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    FOREIGN KEY (requested_by_user_id) REFERENCES app_users(id),
    FOREIGN KEY (decided_by_user_id) REFERENCES app_users(id),
    CHECK (CHAR_LENGTH(TRIM(reason)) > 0),
    CHECK (amount_minor IS NULL OR amount_minor > 0),
    CHECK (quantity IS NULL OR quantity > 0),
    CHECK ((quantity IS NULL) = (quantity_unit_code IS NULL)),
    CHECK ((status = 'pending' AND decided_by_user_id IS NULL AND decided_at_utc IS NULL)
      OR (status <> 'pending' AND decided_by_user_id IS NOT NULL AND decided_at_utc IS NOT NULL)),
    CHECK (decided_at_utc IS NULL OR decided_at_utc >= created_at_utc)
  `),

  table('cash_registers', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(40) CHARACTER SET ascii NOT NULL,
    name VARCHAR(150) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE KEY uq_cash_register_code (code),
    CHECK (is_active IN (0,1))
  `),

  table('cash_shifts', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    cash_register_id BIGINT UNSIGNED NOT NULL,
    responsible_user_id BIGINT UNSIGNED NOT NULL,
    opened_by_user_id BIGINT UNSIGNED NOT NULL,
    closed_by_user_id BIGINT UNSIGNED NULL,
    status ENUM('open','closing','closed') NOT NULL DEFAULT 'open',
    active_register_id BIGINT UNSIGNED GENERATED ALWAYS AS
      (CASE WHEN status IN ('open','closing') THEN cash_register_id ELSE NULL END) STORED,
    opening_amount_minor BIGINT NOT NULL DEFAULT 0,
    expected_amount_minor BIGINT NULL,
    counted_amount_minor BIGINT NULL,
    difference_amount_minor BIGINT GENERATED ALWAYS AS
      (counted_amount_minor - expected_amount_minor) STORED,
    expected_pos_amount_minor BIGINT NULL,
    counted_pos_amount_minor BIGINT NULL,
    closing_reason VARCHAR(1000) NULL,
    closed_at_utc DATETIME(6) NULL,
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE KEY uq_one_active_shift (active_register_id),
    KEY ix_cash_shift_history (cash_register_id, created_at_utc),
    FOREIGN KEY (cash_register_id) REFERENCES cash_registers(id),
    FOREIGN KEY (responsible_user_id) REFERENCES app_users(id),
    FOREIGN KEY (opened_by_user_id) REFERENCES app_users(id),
    FOREIGN KEY (closed_by_user_id) REFERENCES app_users(id),
    CHECK (opening_amount_minor >= 0),
    CHECK (counted_amount_minor IS NULL OR counted_amount_minor >= 0),
    CHECK (expected_pos_amount_minor IS NULL OR expected_pos_amount_minor >= 0),
    CHECK (counted_pos_amount_minor IS NULL OR counted_pos_amount_minor >= 0),
    CHECK (revision > 0),
    CHECK ((status <> 'closed' AND closed_at_utc IS NULL AND closed_by_user_id IS NULL)
      OR (status = 'closed' AND closed_at_utc IS NOT NULL AND closed_by_user_id IS NOT NULL
        AND expected_amount_minor IS NOT NULL AND counted_amount_minor IS NOT NULL)),
    CHECK (closed_at_utc IS NULL OR closed_at_utc >= created_at_utc)
  `),

  // A custody transfer is two balanced rows sharing transfer_group, not revenue.
  // Opening float belongs to cash_shifts, and is not another collection here.
  table('cash_movements', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    operation_id BIGINT UNSIGNED NOT NULL,
    cash_shift_id BIGINT UNSIGNED NOT NULL,
    actor_user_id BIGINT UNSIGNED NOT NULL,
    custody_user_id BIGINT UNSIGNED NULL,
    movement_kind ENUM('sale_receipt','receivable_receipt','supplier_payment',
      'expense_payment','sale_refund','manual_in','manual_out','transfer_in',
      'transfer_out','reversal') NOT NULL,
    amount_minor BIGINT NOT NULL,
    transfer_group CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    reversal_of_id BIGINT UNSIGNED NULL,
    reason VARCHAR(1000) NOT NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE KEY uq_cash_movement_reversal (reversal_of_id),
    KEY ix_cash_movement_shift (cash_shift_id, created_at_utc),
    KEY ix_cash_movement_custody (custody_user_id, created_at_utc),
    KEY ix_cash_movement_operation (operation_id),
    KEY ix_cash_transfer_group (transfer_group),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    FOREIGN KEY (cash_shift_id) REFERENCES cash_shifts(id),
    FOREIGN KEY (actor_user_id) REFERENCES app_users(id),
    FOREIGN KEY (custody_user_id) REFERENCES app_users(id),
    FOREIGN KEY (reversal_of_id) REFERENCES cash_movements(id),
    CHECK (amount_minor <> 0),
    CHECK (CHAR_LENGTH(TRIM(reason)) > 0),
    CHECK ((movement_kind IN ('sale_receipt','receivable_receipt','manual_in','transfer_in') AND amount_minor > 0)
      OR (movement_kind IN ('supplier_payment','expense_payment','sale_refund','manual_out','transfer_out') AND amount_minor < 0)
      OR movement_kind = 'reversal'),
    CHECK ((movement_kind IN ('transfer_in','transfer_out')) = (transfer_group IS NOT NULL)),
    CHECK ((movement_kind = 'reversal') = (reversal_of_id IS NOT NULL))
  `),

  table('import_batches', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    attachment_id BIGINT UNSIGNED NULL,
    import_kind ENUM('products','units_prices','opening_stock','parties','opening_balances') NOT NULL,
    source_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    requested_by_user_id BIGINT UNSIGNED NOT NULL,
    approved_by_user_id BIGINT UNSIGNED NULL,
    status ENUM('staged','validated','approved','applying','completed','failed','cancelled') NOT NULL DEFAULT 'staged',
    mapping_json JSON NULL,
    error_code VARCHAR(80) CHARACTER SET ascii NULL,
    completed_at_utc DATETIME(6) NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE KEY uq_import_source (import_kind, source_sha256),
    KEY ix_import_status (status, created_at_utc),
    FOREIGN KEY (attachment_id) REFERENCES file_attachments(id),
    FOREIGN KEY (requested_by_user_id) REFERENCES app_users(id),
    FOREIGN KEY (approved_by_user_id) REFERENCES app_users(id),
    CHECK (CHAR_LENGTH(source_sha256) = 64),
    CHECK (status NOT IN ('approved','applying','completed') OR approved_by_user_id IS NOT NULL),
    CHECK ((status = 'completed') = (completed_at_utc IS NOT NULL))
  `),

  // Raw spreadsheet cells and validation diagnostics are staging, not live data.
  table('import_rows', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    import_batch_id BIGINT UNSIGNED NOT NULL,
    source_sheet VARCHAR(100) NOT NULL DEFAULT '',
    source_row_number INT UNSIGNED NOT NULL,
    planned_action ENUM('insert','update','skip','reject') NULL,
    status ENUM('pending','valid','invalid','applied','skipped') NOT NULL DEFAULT 'pending',
    input_json JSON NOT NULL,
    validation_errors_json JSON NULL,
    applied_operation_id BIGINT UNSIGNED NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE KEY uq_import_source_row (import_batch_id, source_sheet, source_row_number),
    KEY ix_import_row_status (import_batch_id, status),
    FOREIGN KEY (import_batch_id) REFERENCES import_batches(id),
    FOREIGN KEY (applied_operation_id) REFERENCES business_operations(id),
    CHECK (source_row_number > 0),
    CHECK ((status = 'applied') = (applied_operation_id IS NOT NULL))
  `),

  table('outbox_events', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    operation_id BIGINT UNSIGNED NOT NULL,
    event_type VARCHAR(100) CHARACTER SET ascii NOT NULL,
    event_sequence INT UNSIGNED NOT NULL DEFAULT 1,
    payload_json JSON NULL,
    status ENUM('pending','processing','dispatched','failed') NOT NULL DEFAULT 'pending',
    attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
    available_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    locked_until_utc DATETIME(6) NULL,
    lock_owner VARCHAR(100) CHARACTER SET ascii NULL,
    dispatched_at_utc DATETIME(6) NULL,
    last_error_code VARCHAR(80) CHARACTER SET ascii NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE KEY uq_outbox_operation_event (operation_id, event_type, event_sequence),
    KEY ix_outbox_due (status, available_at_utc, id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    CHECK (event_sequence > 0),
    CHECK ((status = 'dispatched') = (dispatched_at_utc IS NOT NULL)),
    CHECK ((status = 'processing') = (locked_until_utc IS NOT NULL AND lock_owner IS NOT NULL))
  `),

  table('background_jobs', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    job_key VARCHAR(190) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    job_type ENUM('report_export','backup','restore_check','import','notification') NOT NULL,
    operation_id BIGINT UNSIGNED NULL,
    outbox_event_id BIGINT UNSIGNED NULL,
    requested_by_user_id BIGINT UNSIGNED NULL,
    result_attachment_id BIGINT UNSIGNED NULL,
    status ENUM('queued','running','succeeded','failed','unknown','cancelled') NOT NULL DEFAULT 'queued',
    payload_json JSON NULL,
    attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
    available_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    locked_until_utc DATETIME(6) NULL,
    lock_owner VARCHAR(100) CHARACTER SET ascii NULL,
    finished_at_utc DATETIME(6) NULL,
    last_error_code VARCHAR(80) CHARACTER SET ascii NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE KEY uq_background_job_key (job_key),
    KEY ix_background_job_due (status, available_at_utc, id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    FOREIGN KEY (outbox_event_id) REFERENCES outbox_events(id),
    FOREIGN KEY (requested_by_user_id) REFERENCES app_users(id),
    FOREIGN KEY (result_attachment_id) REFERENCES file_attachments(id),
    CHECK ((status = 'running') = (locked_until_utc IS NOT NULL AND lock_owner IS NOT NULL)),
    CHECK (status NOT IN ('succeeded','failed','cancelled') OR finished_at_utc IS NOT NULL)
  `),

  table('printers', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(40) CHARACTER SET ascii NOT NULL,
    name VARCHAR(150) NOT NULL,
    model VARCHAR(150) NULL,
    connection_kind ENUM('system_queue','network','serial','usb') NOT NULL,
    connection_address VARCHAR(255) NULL,
    network_port SMALLINT UNSIGNED NULL,
    station_kind ENUM('cashier','kitchen','bar') NOT NULL,
    preparation_station_id BIGINT UNSIGNED NULL,
    character_encoding VARCHAR(50) CHARACTER SET ascii NULL,
    paper_width_mm SMALLINT UNSIGNED NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE KEY uq_printer_code (code),
    FOREIGN KEY (preparation_station_id) REFERENCES preparation_stations(id),
    CHECK (network_port IS NULL OR network_port > 0),
    CHECK (paper_width_mm IS NULL OR paper_width_mm > 0),
    CHECK (is_active IN (0,1))
  `),

  table('print_jobs', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    job_key VARCHAR(190) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    printer_id BIGINT UNSIGNED NOT NULL,
    operation_id BIGINT UNSIGNED NULL,
    outbox_event_id BIGINT UNSIGNED NULL,
    requested_by_user_id BIGINT UNSIGNED NULL,
    rendered_attachment_id BIGINT UNSIGNED NULL,
    original_print_job_id BIGINT UNSIGNED NULL,
    document_kind ENUM('order_ticket','account_summary','reprint','test') NOT NULL,
    status ENUM('queued','printing','printed','failed','unknown','cancelled') NOT NULL DEFAULT 'queued',
    attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
    available_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    locked_until_utc DATETIME(6) NULL,
    lock_owner VARCHAR(100) CHARACTER SET ascii NULL,
    printed_at_utc DATETIME(6) NULL,
    last_error_code VARCHAR(80) CHARACTER SET ascii NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE KEY uq_print_job_key (job_key),
    KEY ix_print_job_due (status, available_at_utc, id),
    KEY ix_print_job_operation (operation_id),
    FOREIGN KEY (printer_id) REFERENCES printers(id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    FOREIGN KEY (outbox_event_id) REFERENCES outbox_events(id),
    FOREIGN KEY (requested_by_user_id) REFERENCES app_users(id),
    FOREIGN KEY (rendered_attachment_id) REFERENCES file_attachments(id),
    FOREIGN KEY (original_print_job_id) REFERENCES print_jobs(id),
    CHECK ((document_kind = 'reprint') = (original_print_job_id IS NOT NULL)),
    CHECK (document_kind = 'test' OR operation_id IS NOT NULL),
    CHECK ((status = 'printed') = (printed_at_utc IS NOT NULL)),
    CHECK ((status = 'printing') = (locked_until_utc IS NOT NULL AND lock_owner IS NOT NULL))
  `),

  // Target labels identify preconfigured storage; they never contain secrets.
  table('backup_runs', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    background_job_id BIGINT UNSIGNED NULL,
    initiated_by_user_id BIGINT UNSIGNED NULL,
    attachment_id BIGINT UNSIGNED NULL,
    target_label VARCHAR(150) NOT NULL,
    status ENUM('running','succeeded','failed','unknown') NOT NULL DEFAULT 'running',
    encrypted BOOLEAN NOT NULL DEFAULT TRUE,
    includes_attachments BOOLEAN NOT NULL DEFAULT FALSE,
    size_bytes BIGINT UNSIGNED NULL,
    sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    completed_at_utc DATETIME(6) NULL,
    restore_verified_at_utc DATETIME(6) NULL,
    error_code VARCHAR(80) CHARACTER SET ascii NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    KEY ix_backup_status (status, created_at_utc),
    FOREIGN KEY (background_job_id) REFERENCES background_jobs(id),
    FOREIGN KEY (initiated_by_user_id) REFERENCES app_users(id),
    FOREIGN KEY (attachment_id) REFERENCES file_attachments(id),
    CHECK (encrypted IN (0,1)),
    CHECK (includes_attachments IN (0,1)),
    CHECK (sha256 IS NULL OR CHAR_LENGTH(sha256) = 64),
    CHECK (status <> 'succeeded' OR (completed_at_utc IS NOT NULL AND sha256 IS NOT NULL
      AND size_bytes IS NOT NULL AND size_bytes > 0)),
    CHECK (restore_verified_at_utc IS NULL OR (status = 'succeeded' AND restore_verified_at_utc >= completed_at_utc))
  `),

  table('audit_events', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    operation_id BIGINT UNSIGNED NULL,
    actor_user_id BIGINT UNSIGNED NULL,
    action_code VARCHAR(100) CHARACTER SET ascii NOT NULL,
    outcome ENUM('succeeded','denied','failed') NOT NULL,
    reason VARCHAR(1000) NULL,
    metadata_json JSON NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    KEY ix_audit_operation (operation_id, id),
    KEY ix_audit_actor_date (actor_user_id, created_at_utc),
    KEY ix_audit_action_date (action_code, created_at_utc),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    FOREIGN KEY (actor_user_id) REFERENCES app_users(id)
  `)
];
