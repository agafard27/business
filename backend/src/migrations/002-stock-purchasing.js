import { table } from './table.js';

export const stockPurchasingTables = [
  table('purchases', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    document_number VARCHAR(80) NOT NULL UNIQUE,
    supplier_account_id BIGINT UNSIGNED NOT NULL,
    status ENUM('draft','posted','cancelled') NOT NULL DEFAULT 'draft',
    total_minor BIGINT UNSIGNED NOT NULL,
    due_date DATE NULL,
    attachment_id BIGINT UNSIGNED NULL,
    operation_id BIGINT UNSIGNED NOT NULL UNIQUE,
    created_by BIGINT UNSIGNED NOT NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    FOREIGN KEY (supplier_account_id) REFERENCES party_accounts(id),
    FOREIGN KEY (attachment_id) REFERENCES file_attachments(id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    FOREIGN KEY (created_by) REFERENCES app_users(id),
    INDEX ix_purchases_supplier_date (supplier_account_id, created_at_utc)`),
  table('purchase_lines', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    purchase_id BIGINT UNSIGNED NOT NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    purchase_unit_id BIGINT UNSIGNED NOT NULL,
    product_name VARCHAR(180) NOT NULL,
    quantity DECIMAL(18,6) NOT NULL,
    actual_base_quantity DECIMAL(18,6) NOT NULL,
    unit_price_minor BIGINT UNSIGNED NOT NULL,
    total_minor BIGINT UNSIGNED NOT NULL,
    UNIQUE (id, purchase_id),
    UNIQUE (id, product_id),
    FOREIGN KEY (purchase_id) REFERENCES purchases(id),
    FOREIGN KEY (product_id) REFERENCES products(id),
    FOREIGN KEY (purchase_unit_id) REFERENCES units(id),
    CHECK (quantity > 0 AND actual_base_quantity > 0)`),
  table('goods_receipts', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    purchase_id BIGINT UNSIGNED NOT NULL,
    warehouse_id BIGINT UNSIGNED NOT NULL,
    operation_id BIGINT UNSIGNED NOT NULL UNIQUE,
    received_by BIGINT UNSIGNED NOT NULL,
    received_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE (id, purchase_id),
    FOREIGN KEY (purchase_id) REFERENCES purchases(id),
    FOREIGN KEY (warehouse_id) REFERENCES warehouses(id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    FOREIGN KEY (received_by) REFERENCES app_users(id)`),
  table('goods_receipt_lines', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    receipt_id BIGINT UNSIGNED NOT NULL,
    purchase_id BIGINT UNSIGNED NOT NULL,
    purchase_line_id BIGINT UNSIGNED NOT NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    quantity_base DECIMAL(18,6) NOT NULL,
    total_cost_minor BIGINT UNSIGNED NOT NULL,
    UNIQUE (id, product_id),
    FOREIGN KEY (receipt_id, purchase_id) REFERENCES goods_receipts(id, purchase_id),
    FOREIGN KEY (purchase_line_id, purchase_id) REFERENCES purchase_lines(id, purchase_id),
    FOREIGN KEY (purchase_line_id, product_id) REFERENCES purchase_lines(id, product_id),
    CHECK (quantity_base > 0)`),
  table('production_batches', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    batch_code VARCHAR(80) NOT NULL UNIQUE,
    recipe_version_id BIGINT UNSIGNED NULL,
    output_product_id BIGINT UNSIGNED NOT NULL,
    warehouse_id BIGINT UNSIGNED NOT NULL,
    status ENUM('draft','posted','cancelled') NOT NULL DEFAULT 'draft',
    actual_output_quantity_base DECIMAL(18,6) NULL,
    total_cost_minor BIGINT UNSIGNED NULL,
    prepared_by BIGINT UNSIGNED NOT NULL,
    operation_id BIGINT UNSIGNED NOT NULL UNIQUE,
    prepared_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    expires_at_utc DATETIME(6) NULL,
    UNIQUE (id, output_product_id),
    FOREIGN KEY (recipe_version_id, output_product_id) REFERENCES recipe_versions(id, product_id),
    FOREIGN KEY (output_product_id) REFERENCES products(id),
    FOREIGN KEY (warehouse_id) REFERENCES warehouses(id),
    FOREIGN KEY (prepared_by) REFERENCES app_users(id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    CHECK (actual_output_quantity_base IS NULL OR actual_output_quantity_base > 0),
    CHECK (status <> 'posted' OR actual_output_quantity_base IS NOT NULL)`),
  table('stock_lots', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    product_id BIGINT UNSIGNED NOT NULL,
    lot_code VARCHAR(100) NOT NULL,
    receipt_line_id BIGINT UNSIGNED NULL,
    production_batch_id BIGINT UNSIGNED NULL,
    operation_id BIGINT UNSIGNED NOT NULL,
    received_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    expires_at_utc DATETIME(6) NULL,
    UNIQUE (id, product_id),
    UNIQUE (product_id, lot_code),
    UNIQUE (id, product_id, production_batch_id),
    FOREIGN KEY (product_id) REFERENCES products(id),
    FOREIGN KEY (receipt_line_id, product_id) REFERENCES goods_receipt_lines(id, product_id),
    FOREIGN KEY (production_batch_id, product_id) REFERENCES production_batches(id, output_product_id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    CHECK ((receipt_line_id IS NOT NULL) + (production_batch_id IS NOT NULL) <= 1),
    INDEX ix_lots_expiry (product_id, expires_at_utc)`),
  table('production_inputs', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    batch_id BIGINT UNSIGNED NOT NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    lot_id BIGINT UNSIGNED NULL,
    quantity_base DECIMAL(18,6) NOT NULL,
    unit_cost_minor DECIMAL(20,6) NULL,
    FOREIGN KEY (batch_id) REFERENCES production_batches(id),
    FOREIGN KEY (product_id) REFERENCES products(id),
    FOREIGN KEY (lot_id, product_id) REFERENCES stock_lots(id, product_id),
    CHECK (quantity_base > 0),
    CHECK (unit_cost_minor IS NULL OR unit_cost_minor >= 0)`),
  table('production_outputs', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    batch_id BIGINT UNSIGNED NOT NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    lot_id BIGINT UNSIGNED NOT NULL,
    quantity_base DECIMAL(18,6) NOT NULL,
    unit_cost_minor DECIMAL(20,6) NULL,
    UNIQUE (batch_id, lot_id),
    FOREIGN KEY (batch_id, product_id) REFERENCES production_batches(id, output_product_id),
    FOREIGN KEY (lot_id, product_id, batch_id) REFERENCES stock_lots(id, product_id, production_batch_id),
    CHECK (quantity_base > 0),
    CHECK (unit_cost_minor IS NULL OR unit_cost_minor >= 0)`),
  table('stock_documents', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    operation_id BIGINT UNSIGNED NOT NULL UNIQUE,
    document_type ENUM('opening','receipt','sale','production','waste','staff','complimentary','personal','count','customer_return','supplier_return','transfer','correction') NOT NULL,
    reason VARCHAR(500) NOT NULL,
    actor_user_id BIGINT UNSIGNED NOT NULL,
    approval_id BIGINT UNSIGNED NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    FOREIGN KEY (actor_user_id) REFERENCES app_users(id),
    FOREIGN KEY (approval_id) REFERENCES approval_requests(id),
    CHECK (CHAR_LENGTH(TRIM(reason)) > 0)`),
  table('stock_movements', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    document_id BIGINT UNSIGNED NOT NULL,
    sequence_no INT UNSIGNED NOT NULL,
    warehouse_id BIGINT UNSIGNED NOT NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    lot_id BIGINT UNSIGNED NULL,
    quantity_base DECIMAL(18,6) NOT NULL,
    unit_cost_minor DECIMAL(20,6) NULL,
    check_line_id BIGINT UNSIGNED NULL,
    receipt_line_id BIGINT UNSIGNED NULL,
    production_batch_id BIGINT UNSIGNED NULL,
    reversal_of_id BIGINT UNSIGNED NULL,
    created_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    UNIQUE (document_id, sequence_no),
    FOREIGN KEY (document_id) REFERENCES stock_documents(id),
    FOREIGN KEY (warehouse_id) REFERENCES warehouses(id),
    FOREIGN KEY (product_id) REFERENCES products(id),
    FOREIGN KEY (lot_id, product_id) REFERENCES stock_lots(id, product_id),
    FOREIGN KEY (check_line_id) REFERENCES check_lines(id),
    FOREIGN KEY (receipt_line_id, product_id) REFERENCES goods_receipt_lines(id, product_id),
    FOREIGN KEY (production_batch_id) REFERENCES production_batches(id),
    FOREIGN KEY (reversal_of_id) REFERENCES stock_movements(id),
    CHECK (quantity_base <> 0),
    CHECK (unit_cost_minor IS NULL OR unit_cost_minor >= 0),
    CHECK ((check_line_id IS NOT NULL) + (receipt_line_id IS NOT NULL) + (production_batch_id IS NOT NULL) <= 1),
    INDEX ix_stock_product_time (warehouse_id, product_id, created_at_utc),
    INDEX ix_stock_lot_time (lot_id, created_at_utc)`),
  table('stock_counts', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    warehouse_id BIGINT UNSIGNED NOT NULL,
    counted_by BIGINT UNSIGNED NOT NULL,
    status ENUM('draft','posted','cancelled') NOT NULL DEFAULT 'draft',
    stock_document_id BIGINT UNSIGNED NULL UNIQUE,
    counted_at_utc DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    FOREIGN KEY (warehouse_id) REFERENCES warehouses(id),
    FOREIGN KEY (counted_by) REFERENCES app_users(id),
    FOREIGN KEY (stock_document_id) REFERENCES stock_documents(id),
    CHECK (status <> 'posted' OR stock_document_id IS NOT NULL)`),
  table('stock_count_lines', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    count_id BIGINT UNSIGNED NOT NULL,
    product_id BIGINT UNSIGNED NOT NULL,
    lot_id BIGINT UNSIGNED NULL,
    lot_key BIGINT UNSIGNED GENERATED ALWAYS AS (IFNULL(lot_id, 0)) STORED,
    expected_quantity_base DECIMAL(18,6) NOT NULL,
    counted_quantity_base DECIMAL(18,6) NOT NULL,
    reason VARCHAR(500) NULL,
    UNIQUE (count_id, product_id, lot_key),
    FOREIGN KEY (count_id) REFERENCES stock_counts(id),
    FOREIGN KEY (product_id) REFERENCES products(id),
    FOREIGN KEY (lot_id, product_id) REFERENCES stock_lots(id, product_id),
    CHECK (counted_quantity_base >= 0)`),
  table('purchase_returns', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    purchase_id BIGINT UNSIGNED NOT NULL,
    stock_document_id BIGINT UNSIGNED NOT NULL UNIQUE,
    total_minor BIGINT UNSIGNED NOT NULL,
    reason VARCHAR(500) NOT NULL,
    UNIQUE (id, purchase_id),
    FOREIGN KEY (purchase_id) REFERENCES purchases(id),
    FOREIGN KEY (stock_document_id) REFERENCES stock_documents(id),
    CHECK (CHAR_LENGTH(TRIM(reason)) > 0)`),
  table('purchase_return_lines', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    return_id BIGINT UNSIGNED NOT NULL,
    purchase_id BIGINT UNSIGNED NOT NULL,
    purchase_line_id BIGINT UNSIGNED NOT NULL,
    quantity_base DECIMAL(18,6) NOT NULL,
    amount_minor BIGINT UNSIGNED NOT NULL,
    FOREIGN KEY (return_id, purchase_id) REFERENCES purchase_returns(id, purchase_id),
    FOREIGN KEY (purchase_line_id, purchase_id) REFERENCES purchase_lines(id, purchase_id),
    CHECK (quantity_base > 0)`),
  table('expense_categories', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE`),
  table('expenses', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    category_id BIGINT UNSIGNED NOT NULL,
    expense_type ENUM('operating','equipment','staff_payment','staff_advance') NOT NULL,
    supplier_account_id BIGINT UNSIGNED NULL,
    staff_user_id BIGINT UNSIGNED NULL,
    description VARCHAR(500) NOT NULL,
    total_minor BIGINT UNSIGNED NOT NULL,
    due_date DATE NULL,
    attachment_id BIGINT UNSIGNED NULL,
    operation_id BIGINT UNSIGNED NOT NULL UNIQUE,
    created_by BIGINT UNSIGNED NOT NULL,
    incurred_at_utc DATETIME(6) NOT NULL,
    FOREIGN KEY (category_id) REFERENCES expense_categories(id),
    FOREIGN KEY (supplier_account_id) REFERENCES party_accounts(id),
    FOREIGN KEY (staff_user_id) REFERENCES app_users(id),
    FOREIGN KEY (attachment_id) REFERENCES file_attachments(id),
    FOREIGN KEY (operation_id) REFERENCES business_operations(id),
    FOREIGN KEY (created_by) REFERENCES app_users(id),
    CHECK (total_minor > 0),
    CHECK (expense_type NOT IN ('staff_payment','staff_advance') OR staff_user_id IS NOT NULL),
    INDEX ix_expenses_date_category (incurred_at_utc, category_id)`),
  table('equipment', `
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    expense_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(180) NOT NULL,
    serial_number VARCHAR(120) NULL,
    acquired_at DATE NOT NULL,
    retired_at DATE NULL,
    FOREIGN KEY (expense_id) REFERENCES expenses(id)`),
  table('purchase_payment_allocations', `
    purchase_id BIGINT UNSIGNED NOT NULL,
    payment_id BIGINT UNSIGNED NOT NULL,
    amount_minor BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (purchase_id, payment_id),
    FOREIGN KEY (purchase_id) REFERENCES purchases(id),
    FOREIGN KEY (payment_id) REFERENCES payments(id),
    CHECK (amount_minor > 0)`),
  table('expense_payment_allocations', `
    expense_id BIGINT UNSIGNED NOT NULL,
    payment_id BIGINT UNSIGNED NOT NULL,
    amount_minor BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (expense_id, payment_id),
    FOREIGN KEY (expense_id) REFERENCES expenses(id),
    FOREIGN KEY (payment_id) REFERENCES payments(id),
    CHECK (amount_minor > 0)`),
  table('party_entry_sources', `
    party_entry_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
    check_id BIGINT UNSIGNED NULL,
    purchase_id BIGINT UNSIGNED NULL,
    expense_id BIGINT UNSIGNED NULL,
    FOREIGN KEY (party_entry_id) REFERENCES party_entries(id),
    FOREIGN KEY (check_id) REFERENCES checks(id),
    FOREIGN KEY (purchase_id) REFERENCES purchases(id),
    FOREIGN KEY (expense_id) REFERENCES expenses(id),
    CHECK ((check_id IS NOT NULL) + (purchase_id IS NOT NULL) + (expense_id IS NOT NULL) = 1)`)
];
